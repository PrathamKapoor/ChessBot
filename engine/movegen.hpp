// Move generation.
//
// Two legality paths exist:
//
//   generateLegal()          fast path. Decides legality from per-position
//                            information (pinned pieces, checkers) instead of
//                            testing each move by occupancy simulation.
//
//   generateLegalReference() the Phase 1 behaviour: generate pseudo-legal moves
//                            and ask Position::legal() about each one, which
//                            simulates the move. Correct but slow.
//
// Both must always agree. perft and the differential tree tests enforce that,
// and --verify cross-checks them move by move.
#pragma once

#include "position.hpp"
#include "types.hpp"

namespace pocket {

// Appends every pseudo-legal move for the side to move to `out`, in no
// particular order. Callers are responsible for legality filtering.
void generatePseudoLegal(Position& pos, Move* out, int& count);

// Appends every legal move. This is what search and perft use.
void generateLegal(Position& pos, Move* out, int& count);

// Reference implementation, used by the verification harness.
void generateLegalReference(Position& pos, Move* out, int& count);

// Number of moves generated by generateLegal() for the given position, and by
// generateLegalReference(). Returns false if the two disagree.
bool checkLegalAgrees(Position& pos);

inline int legalMoveCount(Position& pos) {
  Move buf[256];
  int n = 0;
  generateLegal(pos, buf, n);
  return n;
}

}  // namespace pocket
